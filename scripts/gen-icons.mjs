import fs from "node:fs";
import path from "node:path";

const dir = path.resolve("assets/icons");
const out = path.resolve("components/icons.generated.ts");

const files = fs.readdirSync(dir).filter((f) => f.endsWith(".svg")).sort();
const entries = files.map((file) => {
  const raw = fs.readFileSync(path.join(dir, file), "utf8");
  const body = raw.slice(raw.indexOf(">") + 1, raw.lastIndexOf("</svg>"));
  const viewBox = raw.match(/viewBox="([^"]+)"/)?.[1] ?? "0 0 20 20";
  return `  ${JSON.stringify(path.basename(file, ".svg"))}: { viewBox: ${JSON.stringify(viewBox)}, body: ${JSON.stringify(body)} },`;
});

const content = `// Generated by scripts/gen-icons.mjs — do not edit by hand.\nexport interface IconData {\n  viewBox: string;\n  body: string;\n}\n\nexport const ICONS: Record<string, IconData> = {\n${entries.join("\n")}\n};\n`;

fs.writeFileSync(out, content);
console.log(`icons: ${files.length} written to ${path.relative(process.cwd(), out)}`);
